"use strict";

/**
 * Dev-mode settings shipped with the build.
 *
 * DevMode → TOOLS → SAVE DEV DEFAULTS collects the editor / layout settings from localStorage and the dev
 * server writes them to js/core/dev-defaults-data.js (window.VF_DEV_DEFAULTS = { key: rawString }), so they
 * go into the deploy ZIP with everything else. On start apply() copies them into localStorage:
 *  - a key the player never changed (missing, or still equal to the value shipped last time) takes the new
 *    shipped value;
 *  - a key the player changed on their own stays untouched.
 */
var vfDevDefaults = (function () {
    var SEEN_KEY = 'vf_dev_defaults_seen_v1';
    // Never shipped: player data, session state, window geometry / tab memory, dev switches.
    var SKIP = /^(vf_profiles_v1|vf_faction_state_v1|vf_dev_mode_v1|vf_iss_session_v1|vf_start_menu_state_v1|vf_preMuteMaster|vf_settings_shots_seen_v1|vf_dev_defaults_seen_v1|vf-boot-id|vf-boot-faction|vf-build|vf-debug|vf-faction|vf-gui-faction|vf-gui-state|vf-faction-hsl)$|(-geom|-pos|-open|-scroll|-zoom|-tab|_collapsed|collapsed_v1|_last_tab|_open_section|_last|vf-ph-)/i;

    function readSeen() {
        try { return JSON.parse(localStorage.getItem(SEEN_KEY) || '{}') || {}; } catch (e) { return {}; }
    }

    function apply() {
        var data = window.VF_DEV_DEFAULTS;
        if (!data || typeof data !== 'object') return;
        var seen = readSeen();
        var changed = false;
        try {
            Object.keys(data).forEach(function (key) {
                var shipped = String(data[key]);
                var cur = localStorage.getItem(key);
                if (cur === null || cur === seen[key]) {
                    if (cur !== shipped) localStorage.setItem(key, shipped);
                    if (seen[key] !== shipped) { seen[key] = shipped; changed = true; }
                }
            });
            // Keys dropped from a newer build stay as they are, but are no longer tracked.
            Object.keys(seen).forEach(function (key) { if (!(key in data)) { delete seen[key]; changed = true; } });
            if (changed) localStorage.setItem(SEEN_KEY, JSON.stringify(seen));
        } catch (e) { /* storage blocked: defaults are optional */ }
    }

    /** Everything in localStorage that counts as a dev setting. */
    function collect() {
        var out = {};
        try {
            for (var i = 0; i < localStorage.length; i++) {
                var key = localStorage.key(i);
                if (!key || !/^(vf|paletteUI)/.test(key) || SKIP.test(key)) continue;
                out[key] = localStorage.getItem(key);
            }
        } catch (e) { /* ignore */ }
        return out;
    }

    function fileText(map) {
        return '"use strict";\n// Generated by DevMode → TOOLS → SAVE DEV DEFAULTS (tools/dev-server.py writes this file). Do not edit by hand.\n'
            + 'window.VF_DEV_DEFAULTS = ' + JSON.stringify(map, null, 1) + ';\n';
    }

    /** Sends the settings to the dev server (writes the data file into the repo); without it, downloads the file. */
    function save(done) {
        var map = collect();
        var count = Object.keys(map).length;
        function download() {
            try {
                var a = document.createElement('a');
                a.href = URL.createObjectURL(new Blob([fileText(map)], { type: 'text/javascript' }));
                a.download = 'dev-defaults-data.js';
                document.body.appendChild(a);
                a.click();
                a.remove();
                done && done(false, count, 'dev server not reachable — file downloaded; put it in js/core/');
            } catch (e) { done && done(false, 0, 'save failed'); }
        }
        if (typeof fetch !== 'function') { download(); return; }
        fetch('/__dev-defaults', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(map) })
            .then(function (r) { return r.json().catch(function () { return {}; }).then(function (j) { return { ok: r.ok && j.ok, j: j }; }); })
            .then(function (r) {
                if (r.ok) done && done(true, count, 'saved ' + count + ' settings to js/core/dev-defaults-data.js');
                else download();
            })
            .catch(download);
    }

    apply();
    return { apply: apply, collect: collect, save: save };
})();
window.vfDevDefaults = vfDevDefaults;
