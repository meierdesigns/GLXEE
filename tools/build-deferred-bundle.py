#!/usr/bin/env python3
"""Build the ordered deferred-script bundle used by every local server."""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INDEX = os.path.join(ROOT, "index.html")
OUTPUT = os.path.join(ROOT, "js", "bundles", "deferred.js")

with open(INDEX, "r", encoding="utf-8") as handle:
    html = handle.read()

paths = re.findall(r'<script\s+defer\s+src="([^"]+)"></script>', html)
chunks = ["/* Generated by tools/build-deferred-bundle.py. Do not edit. */\n"]
for path in paths:
    local = os.path.join(ROOT, path.split("?", 1)[0])
    with open(local, "r", encoding="utf-8") as handle:
        chunks.append("\n/* --- %s --- */\n%s\n" % (path, handle.read()))

os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
with open(OUTPUT, "w", encoding="utf-8") as handle:
    handle.write("".join(chunks))

if "--update-index" in sys.argv:
    bundled = re.sub(r'<script\s+defer\s+src="[^"]+"></script>\s*', "", html)
    bundled = bundled.replace(
        "</body>",
        '<script defer src="js/bundles/deferred.js"></script>\n</body>',
        1,
    )
    with open(INDEX, "w", encoding="utf-8") as handle:
        handle.write(bundled)

if "--restore-index" in sys.argv:
    with open(INDEX, "r", encoding="utf-8") as handle:
        current = handle.read()
    with open(OUTPUT, "r", encoding="utf-8") as handle:
        bundle = handle.read()
    original_tags = "".join(
        '<script defer src="%s"></script>\n' % path
        for path in re.findall(r"/\* --- ([^*]+) --- \*/", bundle)
    )
    current = current.replace(
        '<script defer src="js/bundles/deferred.js"></script>\n',
        original_tags,
    )
    with open(INDEX, "w", encoding="utf-8") as handle:
        handle.write(current)

print("Built %d scripts into %s" % (len(paths), os.path.relpath(OUTPUT, ROOT)))
