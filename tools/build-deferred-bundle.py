#!/usr/bin/env python3
"""Build ordered deferred-script bundles (core + lazy editors)."""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INDEX = os.path.join(ROOT, "index.html")
OUTPUT = os.path.join(ROOT, "js", "bundles", "deferred.js")
OUTPUT_EDITORS = os.path.join(ROOT, "js", "bundles", "deferred-editors.js")
ORDER_FILE = os.path.join(ROOT, "js", "bundles", "script-order.json")

# DevMode / Asset-Gen / viewers — loaded on demand via ensureVfEditors().
EDITOR_PREFIXES = (
    "js/graphics/asset-gen-",
    "js/ui/asset-gen-ui",
    "js/ui/planet-editor",
    "js/ui/component-editor",
    "js/ui/ship-editor",
    "js/ui/enemy-editor",
    "js/ui/theme-editor",
    "js/ui/hangar-test-arena",
    "js/ui/weapon-viewer",
    "js/ui/ship-viewer",
    "js/ui/enemy-viewer",
    "js/ui/faction-viewer",
    "js/ui/energy-viewer",
    "js/ui/defense-viewer",
    "js/ui/ability-viewer",
    "js/ui/explosion-viewer",
    "js/ui/enhanced-palette-ui",
    "js/ui/hud-layout-editor",
)

# Injected into core order if missing (after first core utility scripts).
CORE_INJECT = (
    "js/core/vf-storage.js",
    "js/core/station-anim.js",
    "js/core/editors-loader.js",
)

TOP_DECL = re.compile(r"^(?:const|let) (\w+) =", re.M)
TOP_CLASS = re.compile(r"^class (\w+)((?: extends [^{\n]+)?) \{", re.M)
MARKER_RE = re.compile(r"/\* --- ([^*]+?) --- \*/")


def hoist(text):
    return TOP_CLASS.sub(r"var \1 = class \1\2 {", TOP_DECL.sub(r"var \1 =", text))


def norm(path):
    return path.split("?", 1)[0]


def is_editor(path):
    p = norm(path)
    if p in ("js/bundles/deferred.js", "js/bundles/deferred-editors.js"):
        return False
    return any(p.startswith(prefix) for prefix in EDITOR_PREFIXES)


def markers_from(file_path):
    if not os.path.exists(file_path):
        return []
    with open(file_path, "r", encoding="utf-8") as handle:
        return [
            p for p in MARKER_RE.findall(handle.read())
            if "js/bundles/deferred" not in norm(p)
        ]


def load_paths(html):
    index_paths = re.findall(r'<script\s+defer\s+src="([^"]+)"></script>', html)
    index_has_bundle = any("js/bundles/deferred.js" in norm(p) for p in index_paths)

    if os.path.exists(ORDER_FILE):
        with open(ORDER_FILE, "r", encoding="utf-8") as handle:
            ordered = json.load(handle)
        if isinstance(ordered, list) and ordered:
            return [p for p in ordered if "js/bundles/deferred" not in norm(p)]

    if index_has_bundle and os.path.exists(OUTPUT):
        marker_paths = markers_from(OUTPUT) + markers_from(OUTPUT_EDITORS)
        # Preserve first-seen order.
        seen = set()
        merged = []
        for p in marker_paths:
            k = norm(p)
            if k in seen:
                continue
            seen.add(k)
            merged.append(p)
        extra = [
            p for p in index_paths
            if "js/bundles/deferred" not in norm(p)
            and norm(p) not in seen
        ]
        return merged + extra

    return [p for p in index_paths if "js/bundles/deferred" not in norm(p)]


def inject_core_helpers(paths):
    """Ensure vf-storage / station-anim / editors-loader sit early in core."""
    have = {norm(p) for p in paths}
    missing = [p for p in CORE_INJECT if p not in have]
    if not missing:
        return paths
    # Prefer after extend-class.js; else after first js/core file; else front.
    insert_at = 0
    for i, p in enumerate(paths):
        n = norm(p)
        if n.endswith("extend-class.js") or n.endswith("extend-class-module.js"):
            insert_at = i + 1
            break
        if insert_at == 0 and n.startswith("js/core/"):
            insert_at = i + 1
    out = list(paths)
    for offset, p in enumerate(missing):
        out.insert(insert_at + offset, p)
    return out


def write_bundle(file_path, paths, label):
    chunks = [
        "/* Generated by tools/build-deferred-bundle.py (%s). Do not edit. */\n" % label
    ]
    for path in paths:
        local = os.path.join(ROOT, norm(path))
        if not os.path.isfile(local):
            print("WARN: missing %s" % path, file=sys.stderr)
            continue
        with open(local, "r", encoding="utf-8") as handle:
            chunks.append("\n/* --- %s --- */\n%s\n" % (path, hoist(handle.read())))
    os.makedirs(os.path.dirname(file_path), exist_ok=True)
    with open(file_path, "w", encoding="utf-8") as handle:
        handle.write("".join(chunks))


def main():
    with open(INDEX, "r", encoding="utf-8") as handle:
        html = handle.read()

    paths = inject_core_helpers(load_paths(html))
    core_paths = [p for p in paths if not is_editor(p)]
    editor_paths = [p for p in paths if is_editor(p)]

    # Persist full order so rebuilds keep editor scripts after they leave deferred.js.
    with open(ORDER_FILE, "w", encoding="utf-8") as handle:
        json.dump(paths, handle, indent=2)
        handle.write("\n")

    write_bundle(OUTPUT, core_paths, "core")
    write_bundle(OUTPUT_EDITORS, editor_paths, "editors")

    if "--update-index" in sys.argv:
        bundled = re.sub(r'<script\s+defer\s+src="[^"]+"></script>\s*', "", html)
        bundled = bundled.replace(
            "</body>",
            '<script defer src="js/bundles/deferred.js"></script>\n</body>',
            1,
        )
        with open(INDEX, "w", encoding="utf-8") as handle:
            handle.write(bundled)

    if "--restore-index" in sys.argv:
        with open(INDEX, "r", encoding="utf-8") as handle:
            current = handle.read()
        original_tags = "".join(
            '<script defer src="%s"></script>\n' % path for path in paths
        )
        current = re.sub(
            r'<script\s+defer\s+src="js/bundles/deferred(?:-editors)?\.js"></script>\s*',
            "",
            current,
        )
        current = current.replace("</body>", original_tags + "</body>", 1)
        with open(INDEX, "w", encoding="utf-8") as handle:
            handle.write(current)

    print(
        "Built %d core + %d editors → %s + %s"
        % (
            len(core_paths),
            len(editor_paths),
            os.path.relpath(OUTPUT, ROOT),
            os.path.relpath(OUTPUT_EDITORS, ROOT),
        )
    )


if __name__ == "__main__":
    main()
