#!/usr/bin/env python3
"""Concatenate non-critical stylesheets into css/bundles/app.css for deferred load."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "css", "bundles", "app.css")

# Order matches the former index.html link list (minus critical + editor CSS).
DEFERRED = [
    "css/styles/part-01.css",
    "css/styles/part-02.css",
    "css/styles/part-03.css",
    "css/styles/part-04.css",
    "css/styles/part-05.css",
    "css/styles/part-06.css",
    "css/styles/part-07.css",
    "css/styles/part-08.css",
    "css/styles/part-09.css",
    "css/styles/part-10.css",
    "css/styles/part-11.css",
    "css/styles/part-12.css",
    "css/styles/part-13.css",
    "css/styles/part-14.css",
    "css/styles/part-15.css",
    "css/styles/part-16.css",
    "css/styles/part-17.css",
    "css/styles/part-18.css",
    "css/styles/part-19.css",
    "css/styles/part-20.css",
    "css/styles/part-21.css",
    "css/styles/part-22.css",
    "css/styles/part-23.css",
    "assets/factions/terran/gui.css",
    "assets/factions/kronax/gui.css",
    "assets/factions/voidborn/gui.css",
    "assets/factions/pirate/gui.css",
    "assets/factions/machine/gui.css",
]


def main():
    chunks = [
        "/* Generated by tools/build-css-bundle.py. Do not edit. */\n"
    ]
    total = 0
    count = 0
    for path in DEFERRED:
        local = os.path.join(ROOT, path)
        if not os.path.isfile(local):
            print("WARN: missing %s" % path, file=sys.stderr)
            continue
        with open(local, "r", encoding="utf-8") as handle:
            chunks.append("\n/* --- %s --- */\n%s\n" % (path, handle.read()))
        total += os.path.getsize(local)
        count += 1

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("".join(chunks))

    print("Built %s (%d sheets, %.1f KB)" % (os.path.relpath(OUT, ROOT), count, total / 1024.0))


if __name__ == "__main__":
    main()
